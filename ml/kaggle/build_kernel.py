"""Packages netra_ml + tests into a single self-contained Kaggle script and pushes it.

    python ml/kaggle/build_kernel.py --user <kaggle-username> [--smoke] [--push]

Kaggle script kernels are one file, so the package is embedded as a base64 zip
that the script unpacks before running `netra_ml.pipeline`. Internet is enabled
only so Keras can download ImageNet weights; the Android app never needs it.
"""

from __future__ import annotations

import argparse
import base64
import io
import json
import os
import subprocess
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ML_ROOT = os.path.dirname(HERE)

DATASETS = [
    "tanlikesmath/diabetic-retinopathy-resized",
    "samriddhibagchi/ddr-dataset-credits-to-authors",
    "mariaherrerot/idrid-dataset",
    "mariaherrerot/messidor2preprocess",
    "google-brain/messidor2-dr-grades",
]
COMPETITIONS = ["aptos2019-blindness-detection"]

TEMPLATE = '''# Auto-generated by ml/kaggle/build_kernel.py - do not edit by hand.
import base64, io, os, sys, zipfile, subprocess
PAYLOAD = "{payload}"
dst = "/kaggle/working/netra_ml_src"
zipfile.ZipFile(io.BytesIO(base64.b64decode(PAYLOAD))).extractall(dst)
sys.path.insert(0, dst)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "pytest"], check=False)
from netra_ml import pipeline
pipeline.main({args!r})
'''


def payload() -> str:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for sub in ("netra_ml", "tests"):
            for dirpath, _, files in os.walk(os.path.join(ML_ROOT, sub)):
                for f in files:
                    if f.endswith(".py"):
                        full = os.path.join(dirpath, f)
                        zf.write(full, os.path.relpath(full, ML_ROOT))
    return base64.b64encode(buf.getvalue()).decode()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--user", required=True)
    ap.add_argument("--smoke", action="store_true", help="tiny run that exercises every stage")
    ap.add_argument("--push", action="store_true")
    ap.add_argument("--out", default=os.path.join(os.path.expanduser("~"), "netra_kernel"))
    a = ap.parse_args()

    slug = "netra-dr-smoke" if a.smoke else "netra-dr-train"
    args = ["--max-per-split", "150", "--epochs-override", "1"] if a.smoke else []
    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(a.out, "netra_train.py"), "w") as fh:
        fh.write(TEMPLATE.format(payload=payload(), args=args))
    meta = {"id": f"{a.user}/{slug}", "title": slug, "code_file": "netra_train.py",
            "language": "python", "kernel_type": "script", "is_private": True,
            "enable_gpu": True, "enable_internet": True, "machine_shape": "NvidiaTeslaT4",
            "dataset_sources": DATASETS, "competition_sources": COMPETITIONS, "kernel_sources": []}
    with open(os.path.join(a.out, "kernel-metadata.json"), "w") as fh:
        json.dump(meta, fh, indent=1)
    print(f"kernel written to {a.out} ({slug})")
    if a.push:
        subprocess.run([sys.executable, "-m", "kaggle", "kernels", "push", "-p", a.out], check=True)


if __name__ == "__main__":
    main()
